import pandas as pd
import numpy as np
import seaborn as sns
import matplotlib.pyplot as plt

dt = pd.read_csv("/content/titanic_dataset.csv")

dt.info()

dt.shape

dt.set_index("PassengerId", inplace=True)

dt

print("Data types:")
display(dt.dtypes.to_frame("Data type"))

print("Missing values:")
missing = pd.DataFrame({
    "Missing Count": dt.isna().sum(),
    "Missing Percentage": (dt.isna().mean() * 100)
}).round(2)
display(missing.sort_values("Missing Percentage", ascending=False))

print("Exact duplicate rows:", dt.duplicated().sum())

print("Numeric summary:")
display(dt.describe().T)

dt.nunique()

print(dt["Survived"].value_counts())

per = (dt["Survived"].value_counts() / dt.shape[0] * 100).round(2)
print(per)

print("Pclass unique values:", dt["Pclass"].unique())

dt.rename(columns={"Sex": "Gender"}, inplace=True)
dt.head()

sns.countplot(data=dt, x="Survived")
plt.show()

sns.catplot(x="Gender", col="Survived", kind="count", data=dt, height=5, aspect=0.7)
plt.show()

sns.catplot(x="Survived", hue="Gender", data=dt, kind="count")
plt.show()

dt.boxplot(column="Age", by="Survived")
plt.show()

sns.scatterplot(x=dt["Age"], y=dt["Fare"])
plt.show()

sns.jointplot(x="Age", y="Fare", data=dt)
plt.show()

fig, ax1 = plt.subplots(figsize=(6, 5))
sns.boxplot(ax=ax1, x="Pclass", y="Age", hue="Gender", data=dt)
plt.show()

sns.catplot(data=dt, col="Survived", x="Gender", hue="Pclass", kind="count")
plt.show()

corr = dt.corr(numeric_only=True)
sns.heatmap(corr, annot=True, cmap="coolwarm")
plt.show()

sns.pairplot(dt)
plt.show()

